bool combiningMark(uint32_t c) noexcept
{
    return (c >= 0x300 && c <= 0x36f) || (c >= 0x1ab0 && c <= 0x1aff) ||
        (c >= 0x1dc0 && c <= 0x1dff) || (c >= 0x20d0 && c <= 0x20ff) || (c >= 0xfe20 && c <= 0xfe2f);
}
bool cjk(uint32_t c) noexcept
{
    return (c >= 0x3400 && c <= 0x4dbf) || (c >= 0x4e00 && c <= 0x9fff) ||
        (c >= 0xf900 && c <= 0xfaff) || (c >= 0x20000 && c <= 0x323af) ||
        (c >= 0x3041 && c <= 0x3096) || (c >= 0x309d && c <= 0x30fa) ||
        (c >= 0x30fc && c <= 0x30ff) || (c >= 0x31f0 && c <= 0x31ff) ||
        (c >= 0xff66 && c <= 0xff9d) || (c >= 0x1b000 && c <= 0x1b16f) ||
        (c >= 0x1100 && c <= 0x11ff) || (c >= 0x3131 && c <= 0x318e) ||
        (c >= 0xa960 && c <= 0xa97f) || (c >= 0xac00 && c <= 0xd7af) ||
        (c >= 0xd7b0 && c <= 0xd7ff);
}
std::string contentOnly(std::string_view s)
{
    std::string out;
    for (size_t i = 0; i < s.size();) {
        const auto start = i;
        const auto c = next(s, i);
        if (!space(c) && !punctuation(c)) out.append(s.substr(start, i - start));
    }
    return out;
}
