std::size_t countCodePoints(std::string_view s) noexcept
{
    size_t count = 0;
    for (size_t i = 0; i < s.size(); ++count) next(s, i);
    return count;
}
std::size_t effectiveCharCount(std::string_view s) noexcept
{
    size_t count = 0;
    bool inLatin = false;
    for (size_t i = 0; i < s.size();) {
        const auto c = next(s, i);
        if (combiningMark(c)) continue; // Decomposed Latin accents do not break a word.
        const bool latin = latinOrDigit(c);
        if ((latin && !inLatin) || cjk(c)) ++count;
        inLatin = latin;
    }
    return count;
}
double asciiLetterRatio(std::string_view s) noexcept
{
    size_t letters = 0, total = 0;
    for (size_t i = 0; i < s.size();) {
        const auto c = next(s, i);
        if (space(c) || punctuation(c)) continue;
        ++total;
        if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z')) ++letters;
    }
    return total ? double(letters) / double(total) : 0.;
}
std::string normalizeText(std::string_view raw, const NormalizeOptions &options)
{
    std::string out;
    bool pendingSpace = false;
    for (size_t i = 0; i < raw.size();) {
        if (options.stripEngineTags && raw.substr(i, 2) == "<|") {
            const auto end = raw.find("|>", i + 2);
            if (end != std::string_view::npos) { i = end + 2; continue; }
        }
        const size_t start = i;
        const auto c = next(raw, i);
        if (options.collapseWhitespace && space(c)) { pendingSpace = !out.empty(); continue; }
        if (pendingSpace) out += ' ';
        pendingSpace = false;
        if (c == 0xfffd) out += "\xef\xbf\xbd";
        else out.append(raw.substr(start, i - start));
    }
    const auto content = contentOnly(out);
    if (content.empty()) return {};
    if (options.dropFillerOnly) {
        // Word-break DP handles overlapping custom filler words without greedy false negatives.
        std::vector<bool> reachable(content.size() + 1);
        reachable[0] = true;
        for (size_t i = 0; i < content.size(); ++i) if (reachable[i]) {
            for (const auto &word : options.fillerWords)
                if (!word.empty() && content.compare(i, word.size(), word) == 0)
                    reachable[i + word.size()] = true;
        }
        if (reachable.back()) return {};
    }
    return out;
}
