// Invalid sequences consume one byte, including overlong encodings and surrogates.
uint32_t next(std::string_view s, size_t &i) noexcept
{
    const auto c = static_cast<unsigned char>(s[i++]);
    if (c < 0x80) return c;
    const int n = c >= 0xc2 && c <= 0xdf ? 1 : c >= 0xe0 && c <= 0xef ? 2 :
                  c >= 0xf0 && c <= 0xf4 ? 3 : 0;
    if (!n || s.size() - i < size_t(n)) return 0xfffd;
    uint32_t cp = c & (0x7f >> (n + 1));
    for (int j = 0; j < n; ++j) {
        const auto b = static_cast<unsigned char>(s[i + j]);
        if ((b & 0xc0) != 0x80) return 0xfffd;
        cp = (cp << 6) | (b & 0x3f);
    }
    if ((n == 1 && cp < 0x80) || (n == 2 && cp < 0x800) ||
        (n == 3 && cp < 0x10000) || cp > 0x10ffff || (cp >= 0xd800 && cp <= 0xdfff)) return 0xfffd;
    i += n;
    return cp;
}
bool space(uint32_t c) noexcept
{
    return (c >= 9 && c <= 13) || c == 0x20 || c == 0x85 || c == 0xa0 || c == 0x1680 ||
        (c >= 0x2000 && c <= 0x200a) || c == 0x2028 || c == 0x2029 || c == 0x202f ||
        c == 0x205f || c == 0x3000 || c == 0xfeff;
}
struct Range { uint32_t first, last; };
template<size_t N> bool inRanges(uint32_t c, const Range (&ranges)[N]) noexcept
{
    const auto it = std::lower_bound(ranges, ranges + N, c,
        [](const Range &r, uint32_t value) { return r.last < value; });
    return it != ranges + N && it->first <= c;
}
